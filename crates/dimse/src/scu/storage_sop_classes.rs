//! Storage SOP classes proposed by the C-GET SCU.
//!
//! A C-GET SCU receives the retrieved instances as C-STORE sub-operations on
//! the same association, so it has to propose a presentation context, with the
//! SCP role, for every storage SOP class it is willing to receive. An
//! association carries at most 128 presentation contexts. One of them is taken
//! by the Query/Retrieve GET SOP class, so this list is capped at 127 entries
//! and ordered with the common image classes first. Instances of a class that
//! is not listed cannot be retrieved through C-GET.

use dicom_dictionary_std::uids;

