#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn storage_list_fits_next_to_the_retrieve_context() {
        assert!(
            STORAGE_SOP_CLASSES.len() <= MAX_STORAGE_CONTEXTS,
            "{} storage SOP classes listed, at most {} fit in an association",
            STORAGE_SOP_CLASSES.len(),
            MAX_STORAGE_CONTEXTS
        );
    }

    #[test]
    fn storage_list_has_no_duplicates() {
        let unique: HashSet<&str> = STORAGE_SOP_CLASSES.iter().copied().collect();
        assert_eq!(unique.len(), STORAGE_SOP_CLASSES.len());
    }

    #[test]
    fn storage_list_starts_with_the_common_image_classes() {
        assert_eq!(STORAGE_SOP_CLASSES[0], uids::CT_IMAGE_STORAGE);
        assert!(STORAGE_SOP_CLASSES.contains(&uids::MR_IMAGE_STORAGE));
        assert!(STORAGE_SOP_CLASSES.contains(&uids::SECONDARY_CAPTURE_IMAGE_STORAGE));
    }
}
